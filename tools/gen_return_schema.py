#!/usr/bin/env python3
"""Generate schemas/return.schema.json from the role agents' `## Return contract` blocks.

A return file (`.migration/returns/<ticket>.<role>.yaml`) is an agent's committed report for one
ticket: `role`, `ticket`, `issue`, plus every key of that role's contract. Values stay loosely typed
(the contract text documents them); `gates` must map gate names to an exit code, score, status word
or null.

Usage: gen_return_schema.py            write the schema
       gen_return_schema.py --check    exit 1 if the committed schema is out of date (CI)
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "schemas/return.schema.json"


def role_keys():
    roles = {}
    for f in sorted((ROOT / "agents").glob("afs-*.agent.md")):
        m = re.search(r"## Return contract.*?```ya?ml\n(.*?)```", f.read_text(encoding="utf-8"), re.S)
        roles[f.name.split(".")[0]] = re.findall(r"^([a-z_]+):", m.group(1), re.M) if m else []
    return roles


def build():
    roles = role_keys()
    gate_value = {"type": ["integer", "number", "string", "null"]}
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://github.com/martins-vds/ai-factory-swarm/schemas/return.schema.json",
        "title": "AI Factory Swarm agent return file",
        "description": "Generated by tools/gen_return_schema.py from agents/*.agent.md — do not edit. "
                       "`.migration/returns/<ticket>.<role>.yaml`: an agent's committed report for one ticket.",
        "type": "object",
        "required": ["role", "ticket", "issue"],
        "properties": {
            "role": {"enum": sorted(roles)},
            "ticket": {"type": "string", "pattern": "^[A-Za-z0-9._-]+$"},
            "issue": {"type": ["string", "null"], "pattern": "^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+#[0-9]+$"},
            "gates": {"type": ["object", "null"], "additionalProperties": gate_value},
        },
        "allOf": [
            {"if": {"properties": {"role": {"const": r}}}, "then": {"required": keys}}
            for r, keys in roles.items() if keys
        ],
    }


def main():
    text = json.dumps(build(), indent=2) + "\n"
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("schemas/return.schema.json is out of date; run tools/gen_return_schema.py")
            return 1
        print("return schema up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(build()['allOf'])} roles)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
