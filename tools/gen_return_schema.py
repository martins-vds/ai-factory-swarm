#!/usr/bin/env python3
"""Generate schemas/return.schema.json from the role agents' `## Return contract` blocks.

A return file (`.migration/returns/<ticket>.<role>.yaml`) is an agent's committed report for one
ticket: `role`, `ticket`, `issue`, plus every key of that role's contract. The contract templates are
turned into a strict schema. Placeholders map to types; anything may be null ("fill what you have,
null the rest"), and measured values (exit codes, counts, scores) may also be 'n/a: <reason>'. validate.py
adds what a schema can't (ADR-0017): a finished return has no null gates, and scores match the journal.

  <a | b | c>   (single words)       → one of those values (enum)
  <exit>                             → integer (a command's exit code)
  <n>, <n …>                         → integer ≥ 0
  <score>, <0-1>                     → number in [0, 1]
  <max>                              → number ≥ 0
  <lo-hi> (integers)                 → integer in [lo, hi]
  anything else (<link>, <path>, …)  → string
  {k: …}                             → object with every listed key required (extra keys allowed)
  [x]                                → array of x;  []  → array

Usage: gen_return_schema.py            write the schema
       gen_return_schema.py --check    exit 1 if the committed schema is out of date (CI)
"""
import json
import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "schemas/return.schema.json"
MARK = "__afs_ph__:"


def contract_text(path):
    m = re.search(r"## Return contract.*?```ya?ml\n(.*?)```", path.read_text(encoding="utf-8"), re.S)
    return m.group(1) if m else ""


def parse_template(text):
    """YAML-load a contract template, turning each <placeholder> into a marked string."""
    text = text.replace("<ticket>", "TICKET")
    text = re.sub(r"#.*$", "", text, flags=re.M)
    text = re.sub(r"<([^<>]*)>", lambda m: json.dumps(MARK + m.group(1).strip()), text)
    return yaml.safe_load(text) or {}


def nullable(schema):
    t = schema.get("type")
    if isinstance(t, str):
        schema["type"] = [t, "null"]
    elif isinstance(t, list) and "null" not in t:
        schema["type"] = t + ["null"]
    if "enum" in schema and None not in schema["enum"]:
        schema["enum"] = schema["enum"] + [None]
    return schema


def measured(schema):
    """A measured value (exit code, count, score): the number, null, or 'n/a: <reason>' when it does not apply."""
    return {"anyOf": [nullable(schema), {"type": "string", "pattern": "^n/a: \\S"}]}


def placeholder(ph):
    alts = [a.strip() for a in ph.split("|")]
    if len(alts) > 1 and all(re.fullmatch(r"[A-Za-z0-9_.-]+", a) for a in alts):
        return nullable({"enum": alts})
    if ph == "exit":
        return measured({"type": "integer"})
    if ph == "n" or ph.startswith("n "):
        return measured({"type": "integer", "minimum": 0})
    if ph in ("score", "0-1"):
        return measured({"type": "number", "minimum": 0, "maximum": 1})
    if ph == "max":
        return measured({"type": "number", "minimum": 0})
    m = re.fullmatch(r"(\d+)-(\d+)", ph)
    if m:
        return measured({"type": "integer", "minimum": int(m.group(1)), "maximum": int(m.group(2))})
    return nullable({"type": "string"})


def to_schema(node):
    if isinstance(node, dict):
        return nullable({"type": "object", "required": list(node),
                         "properties": {k: to_schema(v) for k, v in node.items()}})
    if isinstance(node, list):
        s = {"type": "array"}
        if node:
            s["items"] = to_schema(node[0])
        return nullable(s)
    if isinstance(node, str) and node.startswith(MARK):
        return placeholder(node[len(MARK):])
    return nullable({"type": ["string", "number", "integer", "boolean"]})


def roles():
    out = {}
    for f in sorted((ROOT / "agents").glob("afs-*.agent.md")):
        out[f.name.split(".")[0]] = parse_template(contract_text(f))
    return out


def build():
    rs = roles()
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://github.com/martins-vds/ai-factory-swarm/schemas/return.schema.json",
        "title": "AI Factory Swarm agent return file",
        "description": "Generated by tools/gen_return_schema.py from agents/*.agent.md — do not edit. "
                       "`.migration/returns/<ticket>.<role>.yaml`: an agent's committed report for one ticket. "
                       "Values follow the role's contract template; anything may be null.",
        "type": "object",
        "required": ["role", "ticket", "issue"],
        "properties": {
            "role": {"enum": sorted(rs)},
            "ticket": {"type": "string", "pattern": "^[A-Za-z0-9._-]+$"},
            "issue": {"type": ["string", "null"], "pattern": "^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+#[0-9]+$"},
        },
        "allOf": [
            {"if": {"properties": {"role": {"const": r}}},
             "then": {"required": list(t), "properties": {k: to_schema(v) for k, v in t.items()}}}
            for r, t in rs.items() if t
        ],
    }


def main():
    text = json.dumps(build(), indent=2) + "\n"
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("schemas/return.schema.json is out of date; run tools/gen_return_schema.py")
            return 1
        print("return schema up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(build()['allOf'])} roles)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
